// SetLimitSpeed calls openapi /set_limit_speed directly (no AES on that path).
func SetLimitSpeed(tenantID, imei string, speed int) (int, error) {
	env, err := client.PostOpenapi("/set_limit_speed", map[string]interface{}{
		"imei":           imei,
		"speed":          speed,
		"async":          false,
		"commandContext": client.CommandContext(tenantID, ""),
	}, tenantID)
	if err != nil {
		return contract.CodeServerInternal, err
	}
	var cr client.CommandResult
	if len(env.Data) > 0 {
		unmarshalLoose(env.Data, &cr)
		if cr.EcuCode == nil && env.Success {
			if code := extractNestedCode(env.Data); code != "" {
				c := code
				cr.EcuCode = &c
			}
		}
	}
	if !env.Success && cr.EcuCode == nil {
		return contract.MapEcuCode(env.Code), nil
	}
	return contract.MapEcuCode(cr.EcuCodeString()), nil
}

func unmarshalLoose(data []byte, out *client.CommandResult) {
	_ = json.Unmarshal(data, out)
}

func extractNestedCode(data []byte) string {
	var m map[string]interface{}
	if json.Unmarshal(data, &m) != nil {
		return ""
	}
	if s, ok := m["result"].(string); ok {
		var inner map[string]interface{}
		if json.Unmarshal([]byte(s), &inner) == nil {
			return AsString(inner["code"])
		}
	}
	return AsString(m["ecuCode"])
}

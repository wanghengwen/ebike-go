// DeviceVoice plays a ringtone. index is remapped via open.voiceIndexMap.
func DeviceVoice(tenantID, imei string, index, volume int) (int, error) {
	idx := index
	if m := config.GlobalConfig().Open.VoiceIndexMap; m != nil {
		if mapped, ok := m[index]; ok {
			idx = mapped
		}
	}
	body := map[string]interface{}{
		"imei":           imei,
		"idx":            idx,
		"async":          false,
		"commandContext": client.CommandContext(tenantID, ""),
	}
	if volume > 0 {
		body["volume"] = volume
	}
	cr, err := client.PostPaasCommand("/device/paas/voice", body)
	return commandCode(cr, err, false)
}

// Bluetooth configures BLE token/name.
//
// The response's `tm` is generated by the caller from the wall clock: paas
// answers with BluetoothCo{token,name} and no timestamp, so there is nothing
// upstream to forward. The previous signature returned an int64 that was always
// zero, which read like an upstream value the handler was choosing to ignore.
func Bluetooth(tenantID, imei string, token *int64, name string) (int, error) {
	body := map[string]interface{}{
		"imei":           imei,
		"async":          false,
		"commandContext": client.CommandContext(tenantID, ""),
	}
	if token != nil {
		body["token"] = *token
	}
	if name != "" {
		body["name"] = name
	}
	cr, err := client.PostPaasCommand("/device/paas/bluetooth", body)
	return commandCode(cr, err, false)
}


// LockControl orchestrates Xiaoan's combined lock/unlock.
// locked=1 (lock) -> acc=0; locked=0 (unlock) -> acc=1 (also undefend).
func LockControl(tenantID, imei string, locked int, opts CommandOpts) (int, error) {
	acc := 0
	if locked == 0 {
		acc = 1
	}
	return AccControl(tenantID, imei, acc, opts)
}

// BackWheelControl maps locked -> sw with inverted polarity.
// Xiaoan locked 1=lock -> internal sw 0; locked 0=unlock -> sw 1.
func BackWheelControl(tenantID, imei string, locked int, opts CommandOpts) (int, error) {
	sw := 1
	if locked == 1 {
		sw = 0
	}
	body := baseCommand(tenantID, imei, opts)
	body["sw"] = sw
	cr, err := client.PostPaasCommand("/device/paas/rearWheelLock", body)
	return commandCode(cr, err, false)
}

